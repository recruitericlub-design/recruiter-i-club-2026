import { NextRequest, NextResponse } from 'next/server';
import { ModelRouterService } from '@/lib/modelRouter';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { message, customApiKey } = body;

    if (!message || typeof message !== 'string') {
      return NextResponse.json({ error: 'Message is required' }, { status: 400 });
    }

    const systemPrompt = `Ти — Оксана Ковальчук, провідний B2B-координатор міжнародного холдингу Recruiter I Club (Україна, 2026 рік).
Твоя головна місія — втягувати клієнта (директора заводу, агрохолдингу, забудовника чи HRD) у живий короткий діалог та кваліфікувати його, підводячи до отримання розрахунку менеджера в WhatsApp або Telegram.

СУВОРІ ЗАЛІЗНІ ПРАВИЛА (ПОРУШЕННЯ КАТЕГОРИЧНО ЗАБОРОНЕНО):
1. СУВОРА ЛАКОНІЧНІСТЬ: Твоя відповідь має бути МАКСИМУМ 2-3 КОРОТКИХ РЕЧЕННЯ (до 25-35 слів!).
2. ЖОДНИХ ПРОСТИРАДЕЛ ТЕКСТУ: Категорично заборонено видавати всю інформацію відразу, цитувати статті законів чи писати довгі списки. Людина на мобільному не буде читати довгий текст.
3. ЗАВЖДИ ЗАКІНЧУЙ РЕПЛІКУ ОДНИМ ВЛУЧНИМ ЗАПИТАННЯМ: Кожна твоя відповідь повинна ставити коротке, дружнє уточнююче запитання, яке стимулює відповісти.
4. ZERO PRICING: Жодних конкретних сум цін чи прайсів ($/€/₴). Пояснюй у 1 реченні, що вартість індивідуальна і комісію клієнт сплачує ВИКЛЮЧНО В КІНЦІ (після виходу робітників на зміну).
5. Мова: відповідай мовою запитання (українською або російською).

Приклади правильних коротких відповідей:
- На питання про ціну: «Кошторис залежить від кваліфікації та розміру бригади. Головне правило безпеки: комісію агенції ви сплачуєте **виключно в кінці** — після прибуття людей на першу зміну. Яка спеціальність потрібна і скільки людей?»
- На питання про мобілізацію: «Іноземні працівники мають 100% захист від призову за ст. 23 ЗУ — ТЦК не має права ставити їх на облік. Ваші зміни застраховані 24/7. На яку саме ділянку шукаєте людей?»
- На питання про строки: «З Узбекистану робітники прибувають за 21–30 днів під ключ (безвіз). З Індії з візою D-04 — 60–75 днів. Наскільки терміново потрібні люди?»
- Якщо назвали спеціальність (зварювальники, токарі тощо): «Зрозуміла! Зараз у базі є 28 готових кандидатів з відеозвітами практичних іспитів. Скільки робітників потрібно у першу групу — до 5 чи 10+?»
- Якщо назвали кількість (наприклад, 10 осіб): «Прийнято, 10 спеціалістів. Ми складемо графік заїзду та детальний кошторис. Напишіть ваш телефон — куди зручніше надіслати файл, у WhatsApp чи Telegram?»

Запитання користувача: ${message}`;

    // Розумний лаконічний fallback при відсутності AI-ключа
    const fallbackFn = () => {
      const lower = message.toLowerCase();
      if (lower.includes('цін') || lower.includes('вартіст') || lower.includes('скільки') || lower.includes('цена') || lower.includes('стоимость') || lower.includes('кошторис') || lower.includes('смет') || lower.includes('прайс') || lower.includes('тариф')) {
        return `Кошторис залежить від спеціальності та кількості робітників. Головне: комісію ви сплачуєте **виключно в кінці** — після прибуття людей на першу зміну.\n\nЯка саме спеціальність потрібна вашому підприємству і скільки людей?`;
      }
      if (lower.includes('мобіліз') || lower.includes('призов') || lower.includes('тцк') || lower.includes('ст 23') || lower.includes('стаття 23') || lower.includes('повестк')) {
        return `Іноземні працівники мають 100% захист від мобілізації за ст. 23 ЗУ — вони не підлягають військовому обліку, ТЦК не може їх мобілізувати. Ваші зміни захищені 24/7.\n\nНа яку саме ділянку виробництва потрібні люди?`;
      }
      if (lower.includes('строк') || lower.includes('термін') || lower.includes('час') || lower.includes('время') || lower.includes('когда') || lower.includes('коли') || lower.includes('21')) {
        return `З Узбекистану перша група виходить на зміну за **21–30 днів** під ключ (безвізовий режим). З Індії з візою D-04 — 60–75 днів.\n\nНаскільки терміново вам потрібно закрити ці вакансії?`;
      }
      if (lower.includes('гарант') || lower.includes('втеч') || lower.includes('звільн') || lower.includes('убежит') || lower.includes('замен') || lower.includes('замін')) {
        return `Діє офіційна гарантія за B2B-договором: 100% безкоштовна заміна протягом 14–30 днів, якщо робітник не підійшов. А комісія агенції — тільки в кінці.\n\nВ якому місті розташоване ваше підприємство?`;
      }
      if (lower.includes('завод') || lower.includes('виробництв') || lower.includes('производств') || lower.includes('зварювал') || lower.includes('сварщик') || lower.includes('чпк') || lower.includes('чпу') || lower.includes('токар')) {
        return `Чудово! По заводських спеціальностях зараз є 28 готових кандидатів з відео trade-тестів на полігоні.\n\nСкільки робітників потрібно у першу групу — до 5 чи більше 10?`;
      }
      if (lower.includes('будівництв') || lower.includes('стройк') || lower.includes('моноліт') || lower.includes('арматур') || lower.includes('муляр')) {
        return `Прийнято! По будівництву є досвідчені монолітники, арматурники та мулярі з Узбекистану (готові до виїзду за 21–25 днів).\n\nЯкий обсяг бригади вам потрібен?`;
      }
      if (lower.includes('склад') || lower.includes('агро') || lower.includes('кар') || lower.includes('навантажувач') || lower.includes('пакувал')) {
        return `Зрозуміло! Водії навантажувачів та пакувальники для складів є в наявності, без шкідливих звичок і готові до змінних графіків.\n\nСкільки людей плануєте залучити?`;
      }
      if (/\d+/.test(lower)) {
        return `Прийнято, сформуємо розрахунок під вашу кількість. Ми підготуємо детальний кошторис та добірку анкет робітників.\n\nНапишіть ваш номер телефону — куди зручніше надіслати файл, у WhatsApp чи Telegram?`;
      }

      return `Вітаю! Я Оксана, провідний координатор проєктів Recruiter I Club. Допоможу закрити дефіцит кадрів робітниками з Азії зі 100% захистом від мобілізації (ст. 23 ЗУ).\n\nНа яку ділянку потрібні працівники і скільки людей?`;
    };

    const { text, modelUsed } = await ModelRouterService.generateContentWithFailover(
      systemPrompt,
      fallbackFn,
      customApiKey
    );

    // Dynamic Quick Replies based on context
    let quickReplies: string[] = [];
    const lowerReply = text.toLowerCase();
    if (lowerReply.includes('скільки робітників') || lowerReply.includes('скільки людей') || lowerReply.includes('обсяг')) {
      quickReplies = ["3–5 осіб", "6–10 осіб", "15+ робітників"];
    } else if (lowerReply.includes('ділянку') || lowerReply.includes('спеціальність')) {
      quickReplies = ["🏭 Завод / Виробництво", "🏗 Будівництво", "🌾 Склад / Агро"];
    } else if (lowerReply.includes('whatsapp') || lowerReply.includes('телефон') || lowerReply.includes('номер')) {
      quickReplies = ["🟢 У WhatsApp", "🔵 У Telegram", "📞 Дзвінок координатора"];
    } else if (lowerReply.includes('терміново')) {
      quickReplies = ["Терміново (до 25 днів)", "Планово (1–2 місяці)"];
    }

    const telemetry = ModelRouterService.getTelemetry();

    return NextResponse.json({
      reply: text,
      quickReplies,
      modelUsed,
      telemetry
    });
  } catch (error: any) {
    console.error('Chat API Error:', error);
    return NextResponse.json({
      error: error?.message || 'Internal AI Server Error'
    }, { status: 500 });
  }
}
