import { NextRequest, NextResponse } from 'next/server';
import { ModelRouterService } from '@/lib/modelRouter';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const { message, customApiKey } = body;

    if (!message || typeof message !== 'string') {
      return NextResponse.json({ error: 'Message is required' }, { status: 400 });
    }

    const systemPrompt = `Ти — офіційний B2B AI-консультант платформи Recruiter I Club / Recruiter I Club (Україна, 2026 рік).
Твоя роль — консультувати власників бізнесу, директорів заводів, агрохолдингів та HRD щодо легального найму іноземного виробничого персоналу в Україну (Індія, Узбекистан, Казахстан, Бангладеш, Непал, В'єтнам, Філіппіни).

Твої ключові знання та тези:
1. Вартість підбору та верифікації — від $500 за працівника.
2. Маркетингова передплата для фіксації квоти — всього €50 за бронь юридичного слоту.
3. Оформлення пряме на ТОВ замовника (робітник у штаті підприємства, дозвіл на ваше ТОВ). Аутстафінг не пропонується, бо він дорогий (x2) і сірий.
4. Логістичний транзит: авіарейс до Кишинева (Молдова) + організований трансфер наземним спецтранспортом в Україну прямо на виробництво замовника.
5. Гарантії: якщо кандидат не отримав візу, захворів або звільнився в перший місяць — 100% безкоштовна заміна на іншого з пулу.
6. Мова відповіді: українська, діловий стиль B2B, лаконічно, професійно, викликаючи високу довіру.

Запитання користувача: ${message}`;

    // Fallback функція при відсутності ключа або лімітах
    const fallbackFn = () => {
      const lower = message.toLowerCase();
      if (lower.includes('цін') || lower.includes('вартіст') || lower.includes('скільки') || lower.includes('цена') || lower.includes('стоимость')) {
        return `📊 **Ціноутворення Recruiter I Club 2026:**\n\n• **Базовий рекрутинг та Trade Test відбір:** від **$500** за працівника.\n• **Фіксація квоти:** всього **€50** передплати для бронювання юридичного слоту.\n• **Зарплатний фонд працівника:** від $600 до $1,000/міс. залежно від кваліфікації.\n• **Пряме оформлення:** дозвіл видається безпосередньо на ваше ТОВ, що економить до 40% витрат порівняно з сірим аутстафінгом.\n\nБажаєте зафіксувати квоту або розрахувати точну смету під ваше виробництво?`;
      }
      if (lower.includes('строк') || lower.includes('термін') || lower.includes('час') || lower.includes('время')) {
        return `⏱ **Терміни доставки та оформлення:**\n\n• **Узбекистан / Казахстан:** від 3 до 4 тижнів (найшвидший безвізовий/спрощений цикл, немає мовного бар'єру).\n• **Індія / Бангладеш / Непал:** 6–10 тижнів (повний цикл: Trade Test, дозвіл Держпраці, віза D-03 у консульстві, переліт через Кишинів).\n\nНа відміну від популістських обіцянок конкурентів «за 10 днів», ми фіксуємо реальний календарний графік у договорі із фінансовою відповідальністю.`;
      }
      if (lower.includes('гарант') || lower.includes('втеч') || lower.includes('звільн') || lower.includes('убежит')) {
        return `🛡 **Наша багаторівнева система гарантій:**\n\n1. **Кандидат не отримав візу або відмовився:** безкоштовно надаємо іншого відібраного кандидата з нашого живого пулу.\n2. **Випробувальний термін (30 днів):** якщо робітник не підійшов або вирішив звільнитися — безкоштовна заміна.\n3. **Утримання та куратор:** закріплюємо координатора, який вирішує побутові та мовні питання, щоб мінімізувати плинність кадрів.`;
      }
      return `Вітаю! Я B2B AI-консультант Recruiter I Club. Ми допомагаємо українським виробничим, аграрним та логістичним компаніям закривати дефіцит кадрів перевіреними працівниками з Індії, Узбекистану, Бангладеш, Непалу та Філіппін.\n\n• **Ціна старту:** від $500/працівник\n• **Бронь квоти:** €50\n• **Оформлення:** легально в штат вашого ТОВ\n\nЧим можу допомогти: розрахувати необхідну кількість робітників, підібрати країну чи розібрати логістику через Молдову?`;
    };

    const { text, modelUsed } = await ModelRouterService.generateContentWithFailover(
      systemPrompt,
      fallbackFn,
      customApiKey
    );

    const telemetry = ModelRouterService.getTelemetry();

    return NextResponse.json({
      reply: text,
      modelUsed,
      telemetry
    });
  } catch (error: any) {
    console.error('Chat API Error:', error);
    return NextResponse.json({
      error: error?.message || 'Internal AI Server Error'
    }, { status: 500 });
  }
}
